#!/usr/bin/env node
/**
 * Builds the two publishable forms of the results report from public/report/report.ojs,
 * so the notebook has exactly one source of truth.
 *
 *   node scripts/build-observable.js
 *
 * Outputs:
 *   observable/report-observable.ojs  cell-by-cell source for observablehq.com
 *                                     (the classic platform has no file import, so the
 *                                     cells are separated and numbered for pasting)
 *   observable/report-notebook.html   Observable Notebooks 2.0 format - a single file
 *                                     that opens directly in Observable Desktop or
 *                                     builds with @observablehq/notebook-kit
 *
 * Both read metrics.json over HTTPS from the public repository rather than from a local
 * path or a file attachment, so a pasted notebook works with no further setup.
 */

const fs = require('fs');
const path = require('path');
const { parser } = require('@alex.garcia/unofficial-observablehq-compiler');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'public', 'report', 'report.ojs');
const OUT_DIR = path.join(ROOT, 'observable');

const METRICS_URL =
  process.env.METRICS_URL ||
  'https://raw.githubusercontent.com/dhanoliya-ji/solana-replay-engine/main/public/report/metrics.json';

const TITLE = 'Solana Replay Engine — copying a wallet is a latency problem';

/**
 * The host page injects `metricsUrl`; a standalone notebook has no host, so the cell
 * is rewritten to fetch the published file directly.
 */
const METRICS_CELL = `metrics = fetch(${JSON.stringify(METRICS_URL)}).then((response) => response.json())`;

function cellsOf(source) {
  const ast = parser.parseModule(source);
  return ast.cells.map((cell) => {
    const text = source.slice(cell.start, cell.end).trim();
    const name = cell.id && cell.id.name ? cell.id.name : null;
    return { name, text, isOutput: name === null };
  });
}

function rewrite(cells) {
  return cells
    .map((cell) => (cell.name === 'metrics' ? { ...cell, text: METRICS_CELL } : cell))
    .filter((cell) => cell.text.length > 0);
}

/** Cell-by-cell source for pasting into a classic observablehq.com notebook. */
function buildOjs(cells) {
  const header = [
    '// ' + TITLE,
    '//',
    '// Source of truth: https://github.com/dhanoliya-ji/solana-replay-engine',
    '// Generated by scripts/build-observable.js - edit public/report/report.ojs instead.',
    '//',
    '// observablehq.com has no multi-cell import, so each block below is ONE cell.',
    '// Paste a block, press Shift+Enter, repeat. Order does not matter: Observable',
    '// resolves cells by dependency, not by position.',
    '//',
    '// md, html, Plot and d3 come from the Observable standard library, so nothing',
    '// needs to be required. metrics.json is fetched from the public repository.',
    ''
  ].join('\n');

  const blocks = cells.map((cell, i) => {
    const label = cell.name ? `${cell.name}  (data / helper - renders nothing)` : 'output';
    return [
      `// ${'='.repeat(74)}`,
      `// CELL ${String(i + 1).padStart(2, '0')} of ${cells.length}  -  ${label}`,
      `// ${'='.repeat(74)}`,
      '',
      cell.text,
      ''
    ].join('\n');
  });

  return header + '\n' + blocks.join('\n');
}

/**
 * Observable Notebooks 2.0 format: a <notebook> root, a <title>, and one <script>
 * element per cell, each indented by four spaces (the parser trims them).
 */
function buildNotebookHtml(cells) {
  const indent = (text) =>
    text
      .split('\n')
      .map((line) => (line.length ? '    ' + line : ''))
      .join('\n');

  const scripts = cells.map((cell, i) => {
    // Named cells hold data and helpers; suppressing their implicit display is what
    // makes the notebook read as a document rather than a pile of inspectors.
    const attrs = ['type="application/vnd.observable.javascript"', `id="${i + 1}"`];
    if (!cell.isOutput) attrs.push('hidden');
    return `  <script ${attrs.join(' ')}>\n${indent(cell.text)}\n  </script>`;
  });

  return [
    '<!doctype html>',
    '<notebook theme="light-dark(air, midnight)">',
    `  <title>${TITLE.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</title>`,
    ...scripts,
    '</notebook>',
    ''
  ].join('\n');
}

function main() {
  const source = fs.readFileSync(SOURCE, 'utf8');
  const cells = rewrite(cellsOf(source));

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const ojsPath = path.join(OUT_DIR, 'report-observable.ojs');
  const htmlPath = path.join(OUT_DIR, 'report-notebook.html');
  fs.writeFileSync(ojsPath, buildOjs(cells));
  fs.writeFileSync(htmlPath, buildNotebookHtml(cells));

  const named = cells.filter((c) => !c.isOutput).length;
  process.stdout.write(
    `Cells:    ${cells.length} (${named} data/helper, ${cells.length - named} output)\n` +
      `Metrics:  ${METRICS_URL}\n` +
      `Written:  ${path.relative(ROOT, ojsPath)}\n` +
      `Written:  ${path.relative(ROOT, htmlPath)}\n`
  );
}

main();
